const fs = require("node:fs/promises");
const path = require("node:path");
const { randomUUID } = require("node:crypto");

const uploadDirectory = path.join(__dirname, "..", "uploads");

// Save a validated profile picture
const saveProfilePicture = async (file) => {
    if (!file) {
        return null;
    }

    await fs.mkdir(uploadDirectory, { recursive: true });

    const filename = `${randomUUID()}.webp`;
    const filePath = path.join(uploadDirectory, filename);

    await fs.writeFile(filePath, file.buffer, { flag: "wx" });

    return `/uploads/${filename}`;
};

// Remove a stored profile picture
const deleteProfilePicture = async (picturePath) => {
    if (!picturePath) {
        return;
    }

    const filename = path.basename(picturePath);

    // Only allow files generated by this application
    if (!/^[a-f0-9-]{36}\.webp$/i.test(filename)) {
        return;
    }

    const filePath = path.join(uploadDirectory, filename);

    try {
        await fs.unlink(filePath);
    } catch (error) {
        if (error.code !== "ENOENT") {
            throw error;
        }
    }
};

module.exports = {
    saveProfilePicture,
    deleteProfilePicture
};